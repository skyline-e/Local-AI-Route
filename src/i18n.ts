export function detectSystemLanguage(): "zh-CN" | "en-US" {
  try {
    if (typeof navigator !== "undefined") {
      const primary = (navigator.languages?.[0] || navigator.language || "").toLowerCase();
      if (primary.startsWith("zh")) {
        return "zh-CN";
      }
    }
  } catch {}
  return "en-US";
}

